export function parseMonths(sentenceStr) {
  if (!sentenceStr || typeof sentenceStr !== 'string') return 0;
  const rangeMatch = sentenceStr.match(/(\d+)\s*-\s*(\d+)\s*month/i);
  if (rangeMatch) return parseInt(rangeMatch[2], 10);
  const match = sentenceStr.match(/(\d+)\s*month/i);
  if (match) return parseInt(match[1], 10);
  const shortMatch = sentenceStr.match(/(\d+)\s*(?:mo|m)\b/i);
  return shortMatch ? parseInt(shortMatch[1], 10) : 0;
}

export function parseFine(fineStr) {
  if (!fineStr) return 0;
  if (typeof fineStr === 'number') return fineStr;
  const str = String(fineStr);
  const dollarMatch = str.match(/\$\s*([\d,]+(?:\.\d+)?)\s*(k|m)?/i);
  if (dollarMatch) {
    let num = parseFloat(dollarMatch[1].replace(/,/g, '')) || 0;
    if (dollarMatch[2]?.toLowerCase() === 'k') num *= 1000;
    if (dollarMatch[2]?.toLowerCase() === 'm') num *= 1000000;
    return Math.round(num);
  }
  const fineMatch = str.match(/fine[:\s]+(?:\$)?\s*([\d,]+)/i);
  if (fineMatch) {
    return parseInt(fineMatch[1].replace(/,/g, ''), 10) || 0;
  }
  const matches = [...str.replace(/,/g, '').matchAll(/\$?(\d{3,})/g)];
  if (matches.length > 0) {
    const nums = matches.map(m => parseInt(m[1], 10)).filter(n => !isNaN(n) && n > 0);
    return nums.length > 0 ? Math.max(...nums) : 0;
  }
  return 0;
}

export function calculateCharges(selectedCodes, customStars = null) {
  let totalFine = 0;
  let totalMonths = 0;
  let maxSingleStars = 0;
  let accumulatedStars = 0;
  let hasNoBail = false;
  let classes = new Set();
  let chargesSummary = [];

  for (const item of selectedCodes) {
    const fine = parseFine(item.fine);
    const months = parseMonths(item.sentence);
    const stars = item.stars || 0;

    totalFine += fine;
    totalMonths += months;
    accumulatedStars += stars;
    if (stars > maxSingleStars) maxSingleStars = stars;
    if (item.noBail === "1" || (item.note && item.note.toLowerCase().includes("no bail: 1"))) {
      hasNoBail = true;
    }
    if (item.class) {
      classes.add(item.class);
    }

    chargesSummary.push({
      code: item.code,
      description: item.description || item.title,
      fine: item.fine,
      sentence: item.sentence || 'N/A',
      stars: item.stars || 0,
      noBail: item.noBail === "1" || (item.note && item.note.toLowerCase().includes("no bail: 1")),
      class: item.class || 'Standard'
    });
  }

  
  const autoStars = Math.min(5, Math.max(maxSingleStars, accumulatedStars > 0 ? Math.min(5, accumulatedStars) : 0));
  const finalStars = customStars !== null && customStars !== undefined ? Math.min(5, Math.max(0, customStars)) : autoStars;

  return {
    totalFine,
    totalMonths,
    maxStars: finalStars,
    isMaxStars: finalStars >= 5,
    hasNoBail,
    classes: Array.from(classes),
    charges: chargesSummary,
    chargeCount: selectedCodes.length
  };
}

export function getGrandRPEN3DateTime(dateInput = null) {
  const base = dateInput ? new Date(dateInput) : new Date();
  
  const utc1 = new Date(base.getTime() + (base.getTimezoneOffset() + 60) * 60000);
  
  const d = String(utc1.getDate()).padStart(2, '0');
  const m = String(utc1.getMonth() + 1).padStart(2, '0');
  const yFull = utc1.getFullYear();
  const yShort = String(yFull).slice(-2);
  const hh = String(utc1.getHours()).padStart(2, '0');
  const mm = String(utc1.getMinutes()).padStart(2, '0');
  const ss = String(utc1.getSeconds()).padStart(2, '0');
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  const monName = months[utc1.getMonth()];

  return {
    dateShort: `${d}.${m}.${yShort}`,
    dateFormal: `${d} ${monName} ${yFull}`,
    dateStandard: `${d}/${m}/${yFull}`,
    timeShort: `${hh}:${mm}`,
    timeWithSec: `${hh}:${mm}:${ss}`,
    isoDate: `${yFull}-${m}-${d}`,
    dateTimeFull: `${d} ${monName} ${yFull} · ${hh}:${mm} GMT+1`,
    day: d,
    month: m,
    yearFull: yFull,
    yearShort: yShort
  };
}

export function generateDiscordReport(chargesData, officerInfo = {}) {
  const org = (officerInfo.org || 'LSPD').toUpperCase();
  const badge = officerInfo.badge || '[Your Badge / Unit]';
  const suspect = officerInfo.suspect || '[Suspect ID / Name]';
  
  const en3Time = getGrandRPEN3DateTime();
  let dateTimeDisplay = '';
  if (officerInfo.customDate) {
    dateTimeDisplay = officerInfo.customTime ? `${officerInfo.customDate} · ${officerInfo.customTime}` : officerInfo.customDate;
  } else {
    dateTimeDisplay = `${en3Time.dateFormal} · ${en3Time.timeShort} GMT+1`;
  }

  const starsCount = Math.min(5, chargesData.maxStars || 0);
  const starsLabel = starsCount >= 5 ? '★★★★★ (5 Stars MAX)' : (starsCount > 0 ? '★'.repeat(starsCount) + ` (${starsCount} Stars)` : 'None / Processing');

  const lines = [
    `🚔 **SAN ANDREAS LAW ENFORCEMENT ARREST RECORD**`,
    `**Department:** ${org} | **Server:** GrandRP EN3 (GMT+1)`,
    `**Date & Time:** ${dateTimeDisplay}`,
    `**Arresting Officer / Badge:** ${badge}`,
    `**Suspect Identification:** ${suspect}`,
    `──────────────────────────────────────`,
    `**CHARGES FILED (${chargesData.chargeCount}):**`
  ];

  chargesData.charges.forEach((c, idx) => {
    const starsText = c.stars > 0 ? ` [${'★'.repeat(Math.min(5, c.stars))}]` : '';
    const bailText = c.noBail ? ' ⛔ [NO BAIL]' : '';
    lines.push(`${idx + 1}. **${c.code}** - ${c.description} (${c.fine}${c.sentence !== 'N/A' ? ' | ' + c.sentence : ''})${starsText}${bailText}`);
  });

  lines.push(`──────────────────────────────────────`);
  lines.push(`💰 **Total Fines:** $${chargesData.totalFine.toLocaleString()}`);
  lines.push(`⏳ **Recommended Sentence:** ${chargesData.totalMonths > 0 ? chargesData.totalMonths + ' Months' : 'Fine / Processing Only'}`);
  lines.push(`⭐ **Wanted Level Issued:** ${starsLabel}`);
  lines.push(`⚖️ **Bail Status:** ${chargesData.hasNoBail ? '🚫 NO BAIL ALLOWED' : '✅ Eligible for Standard Bail'}`);
  if (chargesData.classes.length > 0) {
    lines.push(`📜 **Severity Classifications:** ${chargesData.classes.join(', ')}`);
  }

  return lines.join('\n');
}

